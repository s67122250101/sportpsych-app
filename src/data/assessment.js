// เรียงข้อแบบสลับด้าน เพื่อลดอคติในการตอบ
export function buildQuestions() {
  const qs = [];
  for (let i = 0; i < 5; i += 1) ORDER.forEach((d) => qs.push({ dim: d, text: DIMENSIONS[d].questions[i] }));
  return qs;
}

// แปลงคะแนนรวมของแต่ละด้านเป็นเปอร์เซ็นต์ 0–100
export const scoreDimension = (values) => Math.round(((values.reduce((a, b) => a + b, 0) - values.length) / (values.length * 4)) * 100);

export function statusOf(dim, pct) {
  if (DIMENSIONS[dim].direction === 'negative') return pct < 40 ? 'good' : pct < 65 ? 'mid' : 'attention';
  return pct >= 65 ? 'good' : pct >= 40 ? 'mid' : 'attention';
}
